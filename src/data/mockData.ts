export function parseIIITRollNumber(email: string): { rollNumber: string; batch: string; discipline: string } | null {
  const cleanEmail = email.toLowerCase().trim();
  if (!cleanEmail.endsWith('@iiitdmj.ac.in')) {
    return null;
  }

  const username = cleanEmail.split('@')[0];
  // Match standard roll numbers like 22bcs045, 21bec012, 23bds018, 20bme050, 24ms002, or faculty/staff names
  const match = username.match(/^(\d{2})([a-zA-Z]{2,4})(\d{2,4})$/);
  if (match) {
    const yearPrefix = match[1];
    const deptCode = match[2].toUpperCase();
    const rollNumber = `${yearPrefix}${deptCode}${match[3]}`.toUpperCase();
    const batch = `20${yearPrefix}`;

    let discipline = 'Engineering & Technology';
    if (deptCode === 'BCS' || deptCode === 'CS') discipline = 'Computer Science & Engineering (CSE)';
    else if (deptCode === 'BEC' || deptCode === 'EC') discipline = 'Electronics & Communication Engineering (ECE)';
    else if (deptCode === 'BME' || deptCode === 'ME') discipline = 'Mechanical Engineering (ME)';
    else if (deptCode === 'BSM' || deptCode === 'SM') discipline = 'Smart Manufacturing (SM)';
    else if (deptCode === 'BDS' || deptCode === 'DS') discipline = 'Bachelor of Design (B.Des)';
    else if (deptCode === 'MT' || deptCode === 'MS') discipline = 'M.Tech / M.Des';
    else if (deptCode === 'PHD') discipline = 'Doctoral Scholar (Ph.D)';

    return { rollNumber, batch, discipline };
  }

  // Handle name-based IIIT corporate handles (e.g., student.name@iiitdmj.ac.in)
  const capitalized = username.replace(/[\._]/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
  return {
    rollNumber: `ID-${username.toUpperCase().slice(0, 8)}`,
    batch: '2024',
    discipline: 'IIITDM Jabalpur Student',
  };
}
